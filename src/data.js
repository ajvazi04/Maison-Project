const productCategory = (product) => {
  const name = product.name.toLowerCase();
  if (name.includes("dress")) return "Dresses";
  if (name.includes("coat")) return "Coats";
  if (["blouse", "zipper", "hoodie"].some((word) => name.includes(word)))
    return "Blouses";
  if (["trouser", "jeans", "texas"].some((word) => name.includes(word)))
    return "Trousers";
  if (["jacket", "blazer"].some((word) => name.includes(word)))
    return "Jackets";
  return product.cat;
};

export const getCategories = (products, gender) =>
  CATS.filter((category) =>
    products.some(
      (product) => product.gender === gender && product.cat === category,
    ),
  );

export const classifyProduct = (product) => ({
  ...product,
  cat: productCategory(product),
  gender:
    product.gender ||
    (product.cat === "Femra" || product.cat === "Bags"
      ? "Femra"
      : product.cat === "Meshkuj"
        ? "Meshkuj"
        : product.cat === "Shoes"
          ? [8, 11, 12].includes(product.id)
            ? "Femra"
            : "Meshkuj"
          : "Unisex"),
  isBestSeller:
    product.isBestSeller ?? [1, 5, 8, 9, 13, 17, 19, 23].includes(product.id),
});
