const productCategory = (product) => {
  const name = product.name.toLowerCase();
  if (name.includes("fustan")) return "Fustane";
  if (name.includes("kaput")) return "Kaputa";
  if (
    ["bluze", "bluzë", "zipper", "hoodie"].some((word) => name.includes(word))
  )
    return "Bluza";
  if (["pantollon", "pantallon", "texas"].some((word) => name.includes(word)))
    return "Pantallona";
  if (
    ["jakne", "xhakete", "xhaketa", "bleizer"].some((word) =>
      name.includes(word),
    )
  )
    return "Xhaketa";
  return product.cat;
};

export const getCategories = (products, gender) =>
  CATS.filter((category) =>
    products.some(
      (product) => product.gender === gender && product.cat === category,
    ),
  );

export const classifyProduct = (product) => ({
  ...product,
  cat: productCategory(product),
  gender:
    product.gender ||
    (product.cat === "Femra" || product.cat === "Çanta"
      ? "Femra"
      : product.cat === "Meshkuj"
        ? "Meshkuj"
        : product.cat === "Këpucë"
          ? [8, 11, 12].includes(product.id)
            ? "Femra"
            : "Meshkuj"
          : "Unisex"),
  isBestSeller:
    product.isBestSeller ?? [1, 5, 8, 9, 13, 17, 19, 23].includes(product.id),
});
